    (() => {
        document.querySelectorAll('.cfo-process-list details').forEach(details => {
            const summary = details.querySelector('summary');
            let animation;

            summary.addEventListener('click', event => {
                event.preventDefault();
                if (animation) animation.cancel();

                const isClosing = details.open;
                const startHeight = details.getBoundingClientRect().height;
                const summaryHeight = summary.getBoundingClientRect().height;
                if (!isClosing) details.open = true;

                details.style.overflow = 'hidden';
                animation = details.animate(
                    [{ height: `${startHeight}px` }, { height: `${isClosing ? summaryHeight : details.scrollHeight}px` }],
                    { duration: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 0 : 360, easing: 'ease-in-out' }
                );
                animation.onfinish = () => {
                    if (isClosing) details.open = false;
                    details.style.overflow = '';
                    animation = null;
                };
            });
        });

        const button = document.querySelector('.cfo-expand');
        const panels = [...document.querySelectorAll('#cfo-benefit-panels details')];
        const sync = () => {
            const expanded = panels.every(panel => panel.open);
            button.setAttribute('aria-expanded', String(expanded));
            button.textContent = expanded ? 'Collapse all benefits -' : 'Expand all benefits +';
        };
        button.addEventListener('click', () => {
            const expand = !panels.every(panel => panel.open);
            panels.forEach(panel => {
                panel.open = expand;
            });
            sync();
        });
        panels.forEach(panel => panel.addEventListener('toggle', sync));
        sync();
    })();
